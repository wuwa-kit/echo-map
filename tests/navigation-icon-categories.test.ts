import { bindIconTestQuery, readIconTestQuery, setIconTestQuery } from './fixtures/icon-query.ts'
import { beforeEach, describe, expect, it } from 'vitest'
import { createPinia, setActivePinia } from 'pinia'
import { useNavigationIconLibraryStore } from '../src/stores/navigation-icon-library.ts'
import { useNavigationIconManagerStore } from '../src/stores/navigation-icon-manager.ts'
import { navigationIconLibrarySchema, iconDisplayName } from '../src/domain/navigation-icon-library.ts'
import { navigationPointTypes } from '../src/domain/navigation-point-types.ts'
import { navigationPickerGroups } from '../src/domain/navigation-icons.ts'

beforeEach(() => {
  setActivePinia(createPinia())
  bindIconTestQuery()
  const library = useNavigationIconLibraryStore()
  library.accept({ ...library.saved, categories: [] })
})

describe('navigation icon categories', () => {
  it('derives filters directly from query changes and writes actions to the same source', () => {
    const manager = useNavigationIconManagerStore()
    setIconTestQuery({ view: 'icons', source: 'unpacked', atlas: '2' })
    expect(manager.filters).toMatchObject({ view: 'icons', source: 'unpacked' })
    manager.setSource('map')
    expect(readIconTestQuery()).toMatchObject({ source: 'map' })
    setIconTestQuery({ view: 'categories', category: 'built-in' })
    expect(manager.filters).toMatchObject({ view: 'categories', source: 'all', category: 'built-in' })
    manager.select('unpack-map-3-3-2')
    expect(readIconTestQuery().icon).toBe('unpack-map-3-3-2')
    manager.setSearch('不存在')
    expect(readIconTestQuery().icon).toBeUndefined()
    expect(manager.selected).toBeNull()
  })
  it('restores the read-only built-in view and clears selections outside it', () => {
    const library = useNavigationIconLibraryStore()
    const manager = useNavigationIconManagerStore()
    manager.select('unpack-map-3-4-4')
    manager.setCategory('built-in')
    expect(manager.selected).toBeNull()
    expect(manager.activeCategory).toBeNull()
    expect(manager.filtered.map(icon => icon.id).sort()).toEqual(Object.values(navigationPointTypes).filter(type => type.builtIn && type.icons.length === 1).flatMap(type => type.icons).sort())
    setIconTestQuery({ category: 'built-in', icon: 'unpack-map-3-3-2' })
    expect(manager.filters.category).toBe('built-in')
    expect(manager.selected?.id).toBe('unpack-map-3-3-2')
    const before = library.draft
    manager.deleteCategory()
    manager.removeCategoryMember('unpack-map-3-3-2')
    expect(library.draft).toBe(before)
    const id = library.createCategory('自定义')
    manager.setCategory(id)
    expect(manager.selected).toBeNull()
  })
  it('separates management tabs without losing category drafts or changing base icons', () => {
    const library = useNavigationIconLibraryStore()
    const manager = useNavigationIconManagerStore()
    const base = library.draft.icons
    const id = library.createCategory('独立分类')
    library.addToCategory(id, ['unpack-map-3-3-2'])
    manager.setCategory(id)
    manager.select('unpack-map-3-3-2')
    manager.setView('icons')
    expect(manager.filters).toMatchObject({ view: 'icons', category: 'all', selectedId: null })
    expect(manager.filtered).toHaveLength(524)
    expect(library.draft.icons).toBe(base)
    expect(library.draft.categories[0]?.icons[0]?.iconId).toBe('unpack-map-3-3-2')
    manager.setSearch('不存在的图标')
    manager.setSource('wiki')
    manager.setView('categories')
    expect(manager.search).toBe('')
    expect(manager.filters.source).toBe('all')
    manager.setCategory(id)
    expect(manager.filtered.map(icon => icon.id)).toEqual(['unpack-map-3-3-2'])
    manager.deleteCategory()
    expect(library.draft.icons).toBe(base)
  })

  it('clears excluded selections for search and status filters without restoring them when filters clear', () => {
    const manager = useNavigationIconManagerStore()
    manager.select('unpack-map-3-3-2')
    manager.setSearch('小型信标')
    expect(manager.selected?.id).toBe('unpack-map-3-3-2')
    manager.setSearch('中枢信标')
    expect(manager.selected).toBeNull()
    expect(manager.detailsOpen).toBe(false)
    manager.setSearch('')
    expect(manager.selected).toBeNull()
    manager.select('unpack-map-3-3-2')
    manager.setStatus('all')
    expect(manager.selected?.id).toBe('unpack-map-3-3-2')
    manager.setStatus('unnamed')
    expect(manager.selected).toBeNull()
    manager.setStatus('all')
    expect(manager.selected).toBeNull()
    expect(manager.filters.selectedId).toBeNull()
  })

  it('retains visible selections and clears excluded details when switching source or category', () => {
    const library = useNavigationIconLibraryStore()
    const manager = useNavigationIconManagerStore()
    const category = library.createCategory('信标')
    library.addToCategory(category, ['unpack-map-3-3-2'])
    manager.select('unpack-map-3-3-2')
    manager.setSource('unpacked')
    manager.setCategory(category)
    expect(manager.selected?.id).toBe('unpack-map-3-3-2')
    manager.toggleReferences()
    manager.toggleAlias(category)
    manager.setCategory('unclassified')
    expect(manager.selected).toBeNull()
    expect(manager.filters.selectedId).toBeNull()
    expect(manager.referencesOpen).toBe(false)
    expect(manager.aliasCategory).toBeNull()
    expect(manager.detailsOpen).toBe(false)
    manager.setCategory('all')
    manager.select('unpack-map-3-3-2')
    manager.setSource('map')
    expect(manager.selected).toBeNull()
    setIconTestQuery({ source: 'map', icon: 'unpack-map-3-3-2' })
    expect(manager.filters.selectedId).toBeNull()
    setIconTestQuery({ source: 'map', icon: 'map-boss-scar' })
    expect(manager.selected?.id).toBe('map-boss-scar')
  })

  it('keeps boss icons in built-in groups while preserving source resources', () => {
    const library = useNavigationIconLibraryStore()
    const manager = useNavigationIconManagerStore()
    expect(library.pool).toHaveLength(524)
    for (const [source, count] of [['placeholder', 1], ['map', 12], ['wiki', 32], ['unpacked', 351], ['echo-catalog', 128]] as const) {
      manager.setSource(source)
      expect(manager.filtered).toHaveLength(count)
    }
    setIconTestQuery({ source: 'map', icon: 'map-boss-scar' })
    expect(manager.selected?.source).toBe('map')
    const original = library.draft.icons
    const id = library.createCategory('混合来源')
    const wikiId = library.pool.find(icon => icon.source === 'wiki')!.id
    const ids = ['unpack-map-3-3-2', 'map-boss-scar', wikiId]
    library.addToCategory(id, ids)
    expect(library.draft.categories[0]?.icons).toEqual([{ iconId: ids[0] }])
    library.rename('map-boss-scar', '自定周本名')
    expect(library.pool.find(icon => icon.id === 'map-boss-scar')?.name).toBe('自定周本名')
    expect(library.draft.icons).toBe(original)
    expect(navigationIconLibrarySchema.safeParse(library.draft).success).toBe(true)
    library.accept(library.draft)
    const group = navigationPickerGroups(library.saved, library.catalog).find(group => group.id === id)
    expect(group?.icons.map(icon => icon.id)).toEqual([ids[0]])
    expect(navigationPickerGroups(library.saved, library.catalog, 'weekly-boss')[0]?.icons.find(icon => icon.id === 'map-boss-scar')?.name).toBe('自定周本名')
    expect(navigationIconLibrarySchema.safeParse({ ...library.draft, categories: [{ id, name: '非法分类', icons: [{ iconId: 'map-boss-scar' }] }] }).success).toBe(false)
    expect(navigationIconLibrarySchema.safeParse({ ...library.draft, overrides: [{ id: 'unknown', name: '' }] }).success).toBe(false)
  })
  it('does not automatically classify pool icons when deleting memberships', () => {
    const library = useNavigationIconLibraryStore()
    const manager = useNavigationIconManagerStore()
    expect(library.draft.categories).toEqual([])
    expect(manager.unclassifiedCount).toBe(0)
    const original = library.draft.icons
    const a = library.createCategory('传送点')
    const b = library.createCategory('常用')
    library.addToCategory(a, ['unpack-map-3-3-2', 'unpack-map-2-3-13', 'unpack-map-3-3-2', 'invalid'])
    library.addToCategory(b, ['unpack-map-3-3-2'])
    expect(library.draft.categories[0]?.icons).toHaveLength(2)
    expect(manager.unclassifiedCount).toBe(0)
    expect(library.draft.categories[1]?.icons).toEqual([])
    expect(navigationIconLibrarySchema.safeParse({ ...library.draft, categories: library.draft.categories.map(category => category.id === b ? { ...category, icons: [{ iconId: 'unpack-map-3-3-2' }] } : category) }).success).toBe(false)
    library.deleteCategory(a)
    expect(manager.unclassifiedCount).toBe(0)
    library.removeFromCategory(b, ['unpack-map-3-3-2'])
    expect(manager.unclassifiedCount).toBe(0)
    expect(library.draft.icons).toBe(original)
  })

  it('uses the same pool name across categories and searches that name', () => {
    const library = useNavigationIconLibraryStore()
    const a = library.createCategory('传送点')
    const b = library.createCategory('常用')
    library.addToCategory(a, ['unpack-map-3-3-2'])
    library.addToCategory(b, ['unpack-map-3-3-2'])
    library.rename('unpack-map-3-3-2', '统一图标名称')
    library.accept(library.draft)
    const groups = navigationPickerGroups(library.saved, library.catalog, undefined, '统一图标名称')
    expect(groups.map(group => group.name)).toEqual(['传送点'])
    expect(groups.every(group => group.icons[0]?.name === '统一图标名称')).toBe(true)
    expect(iconDisplayName({ id: 'unpack-map-3-3-2', name: '' })).toBe('3-3-2')
  })

  it('supports single-icon membership without automatically adding removed icons to unclassified', () => {
    const library = useNavigationIconLibraryStore()
    const manager = useNavigationIconManagerStore()
    const id = library.createCategory('服务')
    manager.setCategory('all')
    manager.select('unpack-map-3-3-2')
    manager.setMembership(id, true)
    manager.select('unpack-map-2-3-13')
    manager.setMembership(id, true)
    manager.setCategory(id)
    expect(manager.filtered.map(icon => icon.id)).toEqual(['unpack-map-2-3-13', 'unpack-map-3-3-2'])
    manager.select('unpack-map-3-3-2')
    manager.setMembership(id, false)
    manager.select('unpack-map-2-3-13')
    manager.setMembership(id, false)
    expect(manager.filtered).toEqual([])
    expect(manager.unclassifiedCount).toBe(0)
    manager.setCategoryInput('新名称')
    manager.renameCategory()
    expect(manager.activeCategoryName).toBe('新名称')
    expect(manager.activeCategory?.name).toBe('服务')
    manager.deleteCategory()
    expect(manager.filters.category).toBe('all')
    expect(library.draft.categories).toEqual([])
  })

  it('rejects duplicate categories, members, missing references and invalid imports atomically', () => {
    const library = useNavigationIconLibraryStore()
    const id = library.createCategory('传送')
    expect(() => library.createCategory(' 传送 ')).toThrow('重复')
    const before = library.draft
    const category = { id, name: '传送', icons: [{ iconId: '1-13-15' }] }
    expect(navigationIconLibrarySchema.safeParse({ ...before, categories: [category] }).success).toBe(false)
    expect(() => library.importDraft({ ...before, categories: [category] })).toThrow()
    expect(library.draft).toBe(before)
    const member = { iconId: 'unpack-map-3-3-2' }
    expect(navigationIconLibrarySchema.safeParse({ ...before, categories: [{ ...category, icons: [member, member] }] }).success).toBe(false)
    expect(navigationIconLibrarySchema.safeParse({ ...before, categories: [...before.categories, ...before.categories] }).success).toBe(false)
  })
})

it('keeps unclassified membership editable while protecting its name and deletion', () => {
  const library = useNavigationIconLibraryStore()
  const manager = useNavigationIconManagerStore()
  library.accept({ ...library.saved, categories: [{ id: 'unclassified', name: '其它', icons: [] }] })
  manager.setCategory('unclassified')
  expect(manager.filtered).toEqual([])
  library.addToCategory('unclassified', ['unpack-map-1-1-1'])
  expect(manager.unclassifiedCount).toBe(1)
  expect(manager.filtered.map(icon => icon.id)).toEqual(['unpack-map-1-1-1'])
  library.renameCategory('unclassified', '改名')
  library.deleteCategory('unclassified')
  expect(manager.activeCategory?.name).toBe('其它')
  expect(navigationPickerGroups(library.draft, library.catalog).find(group => group.id === 'unclassified')?.icons[0]?.name).toBe(library.catalog.find(icon => icon.id === 'unpack-map-1-1-1')?.name)
  library.removeFromCategory('unclassified', ['unpack-map-1-1-1'])
  expect(manager.filtered).toEqual([])
  expect(manager.unclassifiedCount).toBe(0)
  expect(library.pool.some(icon => icon.id === 'unpack-map-1-1-1')).toBe(true)
})

it.each(['echo-settlement', 'weekly-boss', 'normal-boss'] as const)('opens the flat built-in category %s using the URL state', id => {
  const manager = useNavigationIconManagerStore()
  manager.setCategory(id)
  expect(readIconTestQuery().category).toBe(id)
  expect(manager.filtered.map(icon => icon.id).sort()).toEqual([...navigationPointTypes[id].icons].sort())
  const iconId = navigationPointTypes[id].icons[0]
  if (!iconId) throw new Error('Missing built-in icon')
  manager.openCategoryIcon(iconId, id)
  expect(manager.selected?.id).toBe(iconId)
  manager.setCategory('built-in')
  expect(manager.selected).toBeNull()
})
