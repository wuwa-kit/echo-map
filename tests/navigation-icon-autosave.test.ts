it('saves only on request and preserves later edits for the next explicit save', async () => {
  const library = useNavigationIconLibraryStore()
  const manager = useNavigationIconManagerStore()
  await manager.load()
  manager.select('unpack-map-3-3-2')
  let release: (() => void) | undefined
  const gate = new Promise<void>(resolve => { release = resolve })
  vi.mocked(saveNavigationIconLibrary).mockImplementationOnce(async value => { await gate; return { library: value, revision: 'r2' } })
    .mockImplementationOnce(async value => ({ library: value, revision: 'r3' }))
  manager.edit(() => manager.rename('第一次'))
  expect(saveNavigationIconLibrary).not.toHaveBeenCalled()
  const pending = manager.flushEdits()
  library.rename('unpack-map-3-3-2', '最终名称')
  release?.()
  await pending
  expect(saveNavigationIconLibrary).toHaveBeenCalledTimes(1)
  expect(library.dirty).toBe(true)
  await manager.flushEdits()
  expect(saveNavigationIconLibrary).toHaveBeenCalledTimes(2)
  expect(vi.mocked(saveNavigationIconLibrary).mock.calls[1]?.[1]).toBe('r2')
  expect(library.saved.icons.find(icon => icon.id === 'unpack-map-3-3-2')?.name).toBe('最终名称')
  expect(library.dirty).toBe(false)
})

