it('automatically saves only category order and preserves unrelated drafts and JSON array positions', async () => {
  const library = useNavigationIconLibraryStore()
  const manager = useNavigationIconManagerStore()
  await manager.load()
  const first = library.categories[0], last = library.categories.filter(category => category.id !== 'unclassified').at(-1)
  if (!first || !last) throw new Error('Missing categories')
  const before = library.saved
  library.renameCategory(first.id, '未保存名称')
  vi.mocked(saveNavigationIconLibrary).mockImplementationOnce(async value => ({ library: value, revision: 'r2' }))
  await manager.reorderCategory(last.id, first.id, false)
  const submitted = vi.mocked(saveNavigationIconLibrary).mock.calls[0]?.[0]
  expect(submitted?.categories.map(category => category.id)).toEqual(before.categories.map(category => category.id))
  expect(submitted?.categories.find(category => category.id === first.id)?.name).toBe(first.name)
  expect(submitted?.icons).toEqual(before.icons)
  expect(library.categories[0]?.id).toBe(last.id)
  expect(library.draft.categories.find(category => category.id === first.id)?.name).toBe('未保存名称')
  expect(library.dirty).toBe(true)
  expect(library.saved.categories.filter((category, index) => JSON.stringify(category) !== JSON.stringify(before.categories[index]))).toHaveLength(1)
})

