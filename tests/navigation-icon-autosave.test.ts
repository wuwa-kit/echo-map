it('keeps batch selections across filters, retries failures and saves only selected members', async () => {
  const library = useNavigationIconLibraryStore()
  const manager = useNavigationIconManagerStore()
  await manager.load()
  manager.setCategory('unclassified')
  const category = manager.activeCategory
  if (!category) throw new Error('Missing category')
  const ids = library.pool.filter(icon => icon.source !== 'placeholder' && !category.icons.some(member => member.iconId === icon.id)).slice(0, 2).map(icon => icon.id)
  const first = ids[0]
  if (!first) throw new Error('Missing icons')
  library.renameCategory(library.categories.find(item => item.id !== 'unclassified')!.id, '未保存名称')
  const before = library.saved
  manager.openAddIcons()
  for (const id of ids) manager.toggleAddingIcon(id)
  manager.setAddingSource('wiki')
  manager.setMemberSearch('不存在的搜索')
  expect(manager.addingIds).toEqual(ids)
  expect(manager.addingIcons).toEqual([])
  if (category.icons[0]) manager.toggleAddingIcon(category.icons[0].iconId)
  expect(manager.addingIds).toEqual(ids)
  vi.mocked(saveNavigationIconLibrary).mockRejectedValueOnce(new Error('失败'))
  await manager.confirmAddIcons()
  expect(manager.addingCategory?.id).toBe('unclassified')
  expect(manager.addingIds).toEqual(ids)
  expect(library.saved).toBe(before)
  vi.mocked(saveNavigationIconLibrary).mockImplementationOnce(async value => ({ library: value, revision: 'r2' }))
  await manager.confirmAddIcons()
  expect(manager.addingCategory).toBeNull()
  expect(library.saved.categories.find(item => item.id === 'unclassified')?.icons).toHaveLength(category.icons.length + ids.length)
  expect(library.saved.categories.filter(item => item.id !== 'unclassified')).toEqual(before.categories.filter(item => item.id !== 'unclassified'))
  manager.openAddIcons()
  expect(manager.addingIds).toEqual([])
  manager.toggleAddingIcon(first)
  expect(manager.addingIds).toEqual([])
  manager.closeAddIcons()
  expect(saveNavigationIconLibrary).toHaveBeenCalledTimes(2)
})

it('removes from the clicked category in all view without changing the page category', async () => {
  const library = useNavigationIconLibraryStore()
  const manager = useNavigationIconManagerStore()
  await manager.load()
  const category = library.categories.find(category => category.icons.length > 0)
  const iconId = category?.icons[0]?.iconId
  if (!category || !iconId) throw new Error('Missing category member')
  const before = library.saved
  manager.setCategory('all')
  manager.openCategoryIcon(iconId, category.id)
  expect(manager.filters.category).toBe('all')
  expect(manager.selectedCategory?.id).toBe(category.id)
  vi.mocked(saveNavigationIconLibrary).mockImplementationOnce(async value => ({ library: value, revision: 'r2' }))
  await manager.removeCategoryMember(iconId, category.id)
  expect(manager.filters.category).toBe('all')
  expect(manager.selected?.id).toBe(iconId)
  expect(manager.selectedCategory).toBeNull()
  expect(library.saved.categories.find(item => item.id === category.id)?.icons.some(member => member.iconId === iconId)).toBe(false)
  expect(library.saved.categories.filter(item => item.id !== category.id)).toEqual(before.categories.filter(item => item.id !== category.id))
  expect(library.saved.icons).toEqual(before.icons)
  manager.closeDetails()
  manager.openCategoryIcon(iconId, 'built-in')
  expect(manager.selectedCategory).toBeNull()
})

it('stages a unique category change until explicit save and supports unset', async () => {
  const library = useNavigationIconLibraryStore()
  const manager = useNavigationIconManagerStore()
  await manager.load()
  const source = library.categories.find(category => category.icons.length > 0)
  const target = library.categories.find(category => category.id !== source?.id)
  const id = source?.icons[0]?.iconId
  if (!source || !target || !id) throw new Error('Missing categories')
  manager.setCategory(source.id)
  manager.select(id)
  manager.setSelectedIconCategory(target.id)
  expect(manager.selected?.id).toBe(id)
  expect(manager.selectedIconCategoryId).toBe(target.id)
  expect(manager.selectedIconDirty).toBe(true)
  expect(saveNavigationIconLibrary).not.toHaveBeenCalled()
  vi.mocked(saveNavigationIconLibrary).mockImplementation(async value => ({ library: value, revision: 'r2' }))
  await manager.saveSelectedIcon()
  expect(library.saved.categories.filter(category => category.icons.some(member => member.iconId === id)).map(category => category.id)).toEqual([target.id])
  expect(manager.filters.category).toBe(source.id)
  expect(manager.selected).toBeNull()
  manager.setCategory('all')
  manager.select(id)
  manager.setSelectedIconCategory(null)
  await manager.saveSelectedIcon()
  expect(manager.selectedIconCategoryId).toBeNull()
  expect(manager.selectedIconDirty).toBe(false)
  expect(library.saved.categories.some(category => category.icons.some(member => member.iconId === id))).toBe(false)
})

